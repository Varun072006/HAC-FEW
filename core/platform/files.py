"""File service: upload validation, storage through the FileStore connector, metadata in the database.

Reads verify the stored SHA-256, so a file changed on disk after upload (or after a report was approved) is detected
rather than trusted. Artifacts generated by a run get deterministic ids, so re-running the same step overwrites its own
artifact instead of leaving duplicates."""
import hashlib
import io
import re
import uuid
import zipfile
from typing import Optional

from sqlalchemy.orm import Session

from core.connectors import get_file_store
from core.platform import config
from core.platform.models import StoredFile, utcnow

TYPES = {".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", ".csv": "text/csv"}


class UploadRejected(ValueError):
    pass


class FileIntegrityError(Exception):
    pass


def sanitize_name(name: str) -> str:
    base = re.split(r"[\\/]", name or "")[-1]
    base = re.sub(r"[^A-Za-z0-9._\- ]", "_", base).strip(" .")[:120]
    return base or "upload"


def check_upload(name: str, data: bytes) -> str:
    """Raises UploadRejected with a user-readable reason; returns the content type."""
    name = sanitize_name(name)
    ext = ("." + name.rsplit(".", 1)[-1].lower()) if "." in name else ""
    if ext not in TYPES:
        raise UploadRejected(f"'{ext or name}' files are not accepted. Upload an .xlsx or .csv file.")
    if not data:
        raise UploadRejected("The file is empty.")
    if len(data) > config.max_upload_bytes():
        raise UploadRejected(f"The file is larger than the {config.max_upload_bytes() // (1024 * 1024)} MB limit.")
    if ext == ".xlsx":
        if not zipfile.is_zipfile(io.BytesIO(data)):
            raise UploadRejected("This is not a valid .xlsx workbook.")
        names = zipfile.ZipFile(io.BytesIO(data)).namelist()
        if "xl/workbook.xml" not in names:
            raise UploadRejected("This is not a valid .xlsx workbook.")
        if any(n.lower().endswith("vbaproject.bin") for n in names):
            raise UploadRejected("Workbooks containing macros are not accepted.")
    elif b"\x00" in data[:8192]:
        raise UploadRejected("This does not look like a text CSV file.")
    return TYPES[ext]


def artifact_id(*parts: object) -> str:
    return "file_" + hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()[:20]


def save(db: Session, *, name: str, data: bytes, kind: str, content_type: str, user_id: str, run_id: Optional[str] = None,
         node_id: Optional[str] = None, sensitivity: str = "internal", meta: Optional[dict] = None,
         file_id: Optional[str] = None) -> StoredFile:
    store = get_file_store()
    sha = hashlib.sha256(data).hexdigest()
    existing = db.get(StoredFile, file_id) if file_id else None
    if existing is not None and existing.run_id != run_id:
        raise FileIntegrityError("File id collision.")
    key = existing.storage_key if existing else uuid.uuid4().hex
    store.put(key, data)                       # content first: a row never points at a missing file
    row = existing or StoredFile(id=file_id or f"file_{uuid.uuid4().hex[:20]}", storage_key=key, uploaded_by=user_id)
    row.name, row.kind, row.content_type, row.size, row.sha256 = sanitize_name(name), kind, content_type, len(data), sha
    row.run_id, row.node_id, row.sensitivity, row.meta, row.created_at = run_id, node_id, sensitivity, meta or {}, utcnow()
    db.add(row)
    db.commit()
    return row


def load(db: Session, file_id: str) -> tuple[StoredFile, bytes]:
    row = db.get(StoredFile, file_id)
    if row is None:
        raise FileNotFoundError(f"File '{file_id}' does not exist.")
    data = get_file_store().get(row.storage_key)
    if hashlib.sha256(data).hexdigest() != row.sha256:
        raise FileIntegrityError(f"File '{row.name}' no longer matches its recorded SHA-256; refusing to use it.")
    return row, data
